"""SkillAdapter: 技能产物适配器 (MVP 重点实现)

把目标转化为 skill SKILL.md + references 的产物。
验证采用 9 维评估(参考 darwin-skill)。
"""
from __future__ import annotations

from typing import Any

from goal_studio.core.base_adapter import BaseAdapter
from goal_studio.core.contract import Artifact, GoalContract, Patch, PatchOp, ProductType, Report
from goal_studio.core.node_graph import NodeGraph, Node, NodeLayer


class SkillAdapter(BaseAdapter):
    """技能适配器"""

    product_type = "skill"
    name = "Skill Adapter"
    description = "把目标转化为可复用的 SKILL.md 技能文件"

    def draft(self, goal: GoalContract) -> NodeGraph:
        """目标 → 三层 DAG

        L1: 4-7 个任务节点(需求分析/资源调研/技能体编写/验证/固化)
        L2: 每个 L1 分配 1 个 Agent
        L3: 每个 L2 展开具体槽位
        """
        g = NodeGraph()
        # L1: 任务规划
        tasks = [
            ("req-analysis", "需求分析", "解析四要素,明确技能目标"),
            ("resource-research", "资源调研", "搜索类似技能和参考资料"),
            ("skill-authoring", "技能体编写", "起草 SKILL.md 和 references"),
            ("validation", "验证", "9维评估 + 测试prompt"),
            ("build-artifact", "固化产物", "生成最终技能包"),
        ]
        prev_id: str | None = None
        for tid, title, desc in tasks:
            n = Node(
                id=f"l1-{tid}",
                layer=NodeLayer.L1_PLANNING,
                title=title,
                description=desc,
                node_type="task",
            )
            g.add_node(n)
            if prev_id:
                from goal_studio.core.node_graph import Edge
                import uuid

                g.add_edge(
                    Edge(id=f"e-{prev_id}-{n.id}", source=prev_id, target=n.id)
                )
            prev_id = n.id
        g.root_id = "l1-req-analysis"
        return g

    def refine(self, graph: NodeGraph, patch: Patch) -> NodeGraph:
        """应用精化补丁"""
        import copy

        new_graph = NodeGraph.from_dict(graph.to_dict())
        new_graph.version += 1

        if patch.op == PatchOp.UPDATE_NODE and patch.target_node_id:
            node = new_graph.nodes.get(patch.target_node_id)
            if node:
                node.slots.update(patch.slots)
                if "title" in patch.slots:
                    node.title = patch.slots["title"]
                if "description" in patch.slots:
                    node.description = patch.slots["description"]
        elif patch.op == PatchOp.ADD_NODE and patch.new_node:
            node = Node(
                id=patch.new_node.get("id", f"n-{len(new_graph.nodes)}"),
                layer=NodeLayer(patch.new_node.get("layer", 2)),
                title=patch.new_node.get("title", "New Node"),
                description=patch.new_node.get("description", ""),
                slots=patch.new_node.get("slots", {}),
                parent_id=patch.target_node_id,
            )
            new_graph.add_node(node)
        elif patch.op == PatchOp.REMOVE_NODE and patch.target_node_id:
            new_graph.remove_node(patch.target_node_id)
        return new_graph

    def validate(self, graph: NodeGraph) -> Report:
        """9 维评估(简化版)"""
        # MVP: 基于节点数和状态评估
        l1_nodes = graph.get_layer(NodeLayer.L1_PLANNING)
        dims: dict[str, float] = {}
        issues: list[str] = []

        if len(l1_nodes) < 3:
            issues.append("L1 任务节点过少,建议至少 3 个")
            dims["workflow_clarity"] = 40
        elif len(l1_nodes) > 10:
            issues.append("L1 任务节点过多,建议合并")
            dims["workflow_clarity"] = 70
        else:
            dims["workflow_clarity"] = 85

        blocked = [n for n in graph.nodes.values() if n.status.value == "blocked"]
        if blocked:
            issues.append(f"{len(blocked)} 个节点处于阻塞状态")
            dims["executability"] = 50
        else:
            dims["executability"] = 80

        dims["completeness"] = min(100, 60 + len(graph.nodes) * 3)
        dims["failure_coverage"] = 65  # MVP 占位
        dims["resource_integration"] = 60
        dims["architecture"] = 75
        dims["actual_performance"] = 70
        dims["anti_patterns"] = 60
        dims["checkpoint_design"] = 70

        score = sum(dims.values()) / len(dims) if dims else 0
        return Report(
            passed=score >= 70,
            score=score,
            dimensions=dims,
            issues=issues,
            suggestions=["建议补充失败模式编码", "建议增加检查点"] if score < 80 else [],
            evaluator="auto-9dim",
        )

    def build(self, graph: NodeGraph) -> Artifact:
        """DAG → SKILL.md"""
        l1 = graph.get_layer(NodeLayer.L1_PLANNING)
        sections = ["---", "name: generated-skill", "version: 0.1.0", "description: Auto-generated by goal-studio", "---", ""]
        for node in l1:
            sections.append(f"## {node.title}")
            sections.append("")
            sections.append(node.description or "(待填充)")
            sections.append("")
        content = "\n".join(sections)
        return Artifact(
            product_type=ProductType.SKILL,
            content=content,
            files={"SKILL.md": content},
            metadata={"generator": "goal-studio", "node_count": len(graph.nodes)},
            graph_snapshot=graph.to_dict(),
        )

    def export(self, artifact: Artifact, target: str) -> str:
        """导出技能包"""
        from pathlib import Path
        from urllib.parse import urlparse

        parsed = urlparse(target)
        if parsed.scheme == "file":
            out_dir = Path(parsed.path)
            out_dir.mkdir(parents=True, exist_ok=True)
            for path, content in artifact.files.items():
                (out_dir / path).write_text(content, encoding="utf-8")
            return str(out_dir)
        raise ValueError(f"Unsupported export target: {target}")

    def install(self, artifact: Artifact, env: dict[str, str]) -> str:
        """安装到 skill 目录"""
        skill_dir = env.get("skill_dir")
        if not skill_dir:
            return "skill_dir not provided in env"
        from pathlib import Path

        out = Path(skill_dir) / artifact.metadata.get("skill_name", "generated-skill")
        out.mkdir(parents=True, exist_ok=True)
        for path, content in artifact.files.items():
            (out / path).write_text(content, encoding="utf-8")
        return f"Installed to {out}"

    def get_schema(self) -> dict[str, Any]:
        return {
            "node_types": ["task", "agent", "tool", "decision"],
            "slots": {
                "task": ["title", "description", "expected_output"],
                "agent": ["role", "tools", "system_prompt"],
                "tool": ["name", "params", "output_schema"],
            },
        }


